#!/bin/sh
set -eu

# Feed this file to `docker compose ... exec -T archive-postgres sh`.
# Probe tables and records are rolled back, leaving no verification data.
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set ON_ERROR_STOP=1 <<'SQL'
BEGIN;
SET LOCAL ROLE archive_owner;
CREATE TABLE archive._database_setup_probe (id BIGINT GENERATED BY DEFAULT AS IDENTITY, body TEXT);
CREATE TABLE quality._database_setup_probe (id BIGINT GENERATED BY DEFAULT AS IDENTITY, body TEXT);
CREATE TABLE ops._database_setup_probe (id INTEGER, body TEXT);
GRANT SELECT, INSERT, UPDATE ON ops._database_setup_probe TO archive_ingest;
GRANT SELECT ON ops._database_setup_probe TO archive_reader, archive_quality;

SET LOCAL ROLE archive_ingest;
INSERT INTO archive._database_setup_probe (body) VALUES ('original');
INSERT INTO ops._database_setup_probe VALUES (1, 'queued');
UPDATE ops._database_setup_probe SET body = 'completed' WHERE id = 1;

DO $check$
BEGIN
    BEGIN
        UPDATE archive._database_setup_probe SET body = 'changed';
        RAISE EXCEPTION 'FAIL: ingest can update original evidence';
    EXCEPTION WHEN insufficient_privilege THEN NULL;
    END;
    BEGIN
        DELETE FROM archive._database_setup_probe;
        RAISE EXCEPTION 'FAIL: ingest can delete original evidence';
    EXCEPTION WHEN insufficient_privilege THEN NULL;
    END;
    BEGIN
        TRUNCATE archive._database_setup_probe;
        RAISE EXCEPTION 'FAIL: ingest can truncate original evidence';
    EXCEPTION WHEN insufficient_privilege THEN NULL;
    END;
    BEGIN
        CREATE TABLE archive._unauthorized_probe (id INTEGER);
        RAISE EXCEPTION 'FAIL: ingest can create evidence tables';
    EXCEPTION WHEN insufficient_privilege THEN NULL;
    END;
END
$check$;

SET LOCAL ROLE archive_quality;
SELECT body AS quality_reads_original FROM archive._database_setup_probe;
INSERT INTO quality._database_setup_probe (body) VALUES ('version 1');
DO $check$
BEGIN
    BEGIN
        INSERT INTO archive._database_setup_probe (body) VALUES ('unauthorized');
        RAISE EXCEPTION 'FAIL: quality worker can append chat evidence';
    EXCEPTION WHEN insufficient_privilege THEN NULL;
    END;
    BEGIN
        UPDATE quality._database_setup_probe SET body = 'overwritten';
        RAISE EXCEPTION 'FAIL: quality worker can overwrite a result version';
    EXCEPTION WHEN insufficient_privilege THEN NULL;
    END;
END
$check$;

SET LOCAL ROLE archive_reader;
SELECT body AS reader_reads_original FROM archive._database_setup_probe;
SELECT body AS reader_reads_quality FROM quality._database_setup_probe;
DO $check$
BEGIN
    BEGIN
        INSERT INTO archive._database_setup_probe (body) VALUES ('unauthorized');
        RAISE EXCEPTION 'FAIL: reader can write original evidence';
    EXCEPTION WHEN insufficient_privilege THEN NULL;
    END;
    BEGIN
        INSERT INTO ops._database_setup_probe VALUES (2, 'unauthorized');
        RAISE EXCEPTION 'FAIL: reader can write task state';
    EXCEPTION WHEN insufficient_privilege THEN NULL;
    END;
END
$check$;
ROLLBACK;
SELECT current_database() AS database, 'PASS: runtime privileges and rollback' AS verification;
SQL

# Test actual TCP/password authentication, not only local initialization access.
PGPASSWORD="$ARCHIVE_INGEST_PASSWORD" psql --host 127.0.0.1 --username archive_ingest \
    --dbname "$POSTGRES_DB" --set ON_ERROR_STOP=1 --command 'SELECT current_user, current_database();'
PGPASSWORD="$ARCHIVE_READER_PASSWORD" psql --host 127.0.0.1 --username archive_reader \
    --dbname "$POSTGRES_DB" --set ON_ERROR_STOP=1 --command 'SELECT current_user, current_database();'
PGPASSWORD="$ARCHIVE_QUALITY_PASSWORD" psql --host 127.0.0.1 --username archive_quality \
    --dbname "$POSTGRES_DB" --set ON_ERROR_STOP=1 --command 'SELECT current_user, current_database();'

printf '%s\n' 'PASS: all three runtime accounts authenticated; no probe data retained.'
